const dictionaries: Record<Locale, Dictionary> = { en, 'zh-CN': zhCN, 'zh-TW': zhTW }

/** Map an OS/browser locale tag (e.g. "zh-HK", "en-US") to a supported UI locale. */
export function resolveLocale(tag: string): Locale {
  const lower = tag.toLowerCase()
  if (lower.startsWith('zh')) {
    return /^zh-(tw|hk|mo|hant)/.test(lower) ? 'zh-TW' : 'zh-CN'
  }
  return 'en'
}

export type Translate = (key: MessageKey, params?: Record<string, string | number>) => string

export function createTranslator(locale: Locale): Translate {
  const dictionary = dictionaries[locale]
  return (key, params) => {
    let message = dictionary[key] ?? en[key]
    if (params) {
      for (const [name, value] of Object.entries(params)) message = message.replaceAll(`{${name}}`, String(value))
    }
    return message
  }
}
